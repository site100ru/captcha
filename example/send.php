<?php
// =============================================================================
// ПРИМЕР: ОБРАБОТЧИК ФОРМЫ С ПРОВЕРКОЙ КАПЧИ И ТЕЛЕФОНА
// =============================================================================
//
// Сюда отправляется форма из index.php (атрибут action="send.php").
// Порядок работы:
//   1. Проверяем ответ на пример (капчу).
//   2. Проверяем, что телефон введён полностью по маске.
//   3. Если всё в порядке — отправляем заявку (здесь — место для вашего кода).
//   4. Записываем сообщение о результате в сессию и возвращаем посетителя
//      на страницу с формой, где это сообщение будет показано.
// =============================================================================

// Подключаем функции проверки капчи и телефона.
// __DIR__ — папка этого файла; путь ведёт в соседнюю папку captcha.
// captcha-check.php сам включит сессию, если она ещё не включена.
require_once __DIR__ . '/../captcha/captcha-check.php';

// Куда вернуть посетителя после обработки: на страницу, с которой пришла форма.
// HTTP_REFERER может отсутствовать (некоторые браузеры его не передают) —
// тогда возвращаем на index.php.
$back = ! empty( $_SERVER['HTTP_REFERER'] ) ? $_SERVER['HTTP_REFERER'] : 'index.php';

// Обрабатываем только отправку формы (метод POST).
// Если файл открыли просто по ссылке — сразу возвращаем на страницу с формой.
if ( $_SERVER['REQUEST_METHOD'] !== 'POST' ) {
	// Перенаправляем браузер обратно
	header( 'Location: ' . $back );
	// Прекращаем выполнение файла
	exit;
}

// 1. КАПЧА. Передаём ответ посетителя или null, если поля captcha в форме не было.
if ( ! captcha_is_valid( isset( $_POST['captcha'] ) ? $_POST['captcha'] : null ) ) {
	// Запоминаем текст ошибки — его покажет index.php
	$_SESSION['captcha_message'] = 'Ошибка! Неверный ответ на пример. Попробуйте ещё раз.';
	// Возвращаем посетителя к форме
	header( 'Location: ' . $back );
	// Заявку не отправляем
	exit;
}

// 2. ТЕЛЕФОН. Передаём номер или null, если поля tel в форме не было.
if ( ! captcha_phone_is_valid( isset( $_POST['tel'] ) ? $_POST['tel'] : null ) ) {
	// Запоминаем текст ошибки — его покажет index.php
	$_SESSION['captcha_message'] = 'Ошибка! Введите телефон полностью в формате +7(999)999-99-99.';
	// Возвращаем посетителя к форме
	header( 'Location: ' . $back );
	// Заявку не отправляем
	exit;
}

// Обе проверки пройдены — забираем данные формы.
// Имя необязательное: если его не ввели (или прислали не текстом) — «Не указано».
$name = isset( $_POST['name'] ) && is_string( $_POST['name'] ) && trim( $_POST['name'] ) !== '' ? trim( $_POST['name'] ) : 'Не указано';

// Телефон уже проверен, он точно имеет вид +7(999)999-99-99
$tel = $_POST['tel'];

// 3. ОТПРАВКА ЗАЯВКИ.
// Здесь ваш код отправки: письмо через mail(), сообщение в Telegram и т. п.
// Например:
//   $sent = mail( 'you@example.com', 'Заявка с сайта', "Имя: $name\nТелефон: $tel" );
// В примере просто считаем, что заявка отправлена.
$sent = true;

// 4. Запоминаем сообщение о результате — его покажет index.php
if ( $sent ) {
	// Заявка ушла
	$_SESSION['captcha_message'] = 'Спасибо за заявку! Мы свяжемся с Вами в ближайшее время.';
} else {
	// Отправка не удалась (например, на сервере не настроена почта)
	$_SESSION['captcha_message'] = 'Ошибка! Не удалось отправить заявку. Попробуйте ещё раз.';
}

// Возвращаем посетителя на страницу с формой
header( 'Location: ' . $back );

// Прекращаем выполнение файла
exit;
