/**
 * МАСКА ДЛЯ ПОЛЕЙ ВВОДА ТЕЛЕФОНА
 *
 * Применяет маску +7(999)999-99-99 ко всем полям с классом "telMask":
 *   <input type="text" name="tel" class="telMask">
 *
 * Посетитель вводит только цифры, а скобки, дефисы и «+7» подставляются сами.
 * Если номер не дописан до конца, сервер (captcha_phone_is_valid() в
 * captcha-check.php) не примет заявку.
 *
 * Работает на библиотеке Inputmask — её нужно подключить ДО этого файла:
 *   <script src="/captcha/inputmask.min.js"></script>
 *   <script src="/captcha/tel-mask.js"></script>
 *
 * Если меняете маску здесь — поменяйте и шаблон в captcha_phone_is_valid(),
 * иначе сервер будет отклонять правильно введённые номера.
 *
 * Подробная инструкция по установке — в файле README.md в корне репозитория.
 */

// Оборачиваем код в функцию, которая сразу же вызывается,
// чтобы наши переменные не смешивались с переменными других скриптов сайта
(function () {
  // Строгий режим: браузер сообщает о типичных ошибках в коде, а не молчит
  'use strict';

  // Находит поля телефона и включает на них маску
  function init() {
    // Библиотека Inputmask не подключена — сообщаем в консоль браузера (F12)
    // и выходим, чтобы не сломать остальные скрипты страницы
    if (typeof Inputmask === 'undefined') {
      console.error('tel-mask.js: не найдена библиотека Inputmask. Подключите inputmask.min.js перед tel-mask.js.');
      return;
    }

    // Все поля с классом telMask на странице
    var fields = document.getElementsByClassName('telMask');

    // Создаём маску: 9 означает «любая цифра», остальные символы
    // (+7, скобки, дефисы) подставляются автоматически
    var im = new Inputmask('+7(999)999-99-99');

    // Применяем маску сразу ко всем найденным полям
    im.mask(fields);
  }

  // Если страница ещё загружается — ждём, пока браузер построит всю разметку
  if (document.readyState === 'loading') {
    // DOMContentLoaded — событие «вся разметка страницы готова»
    document.addEventListener('DOMContentLoaded', init);
  } else {
    // Разметка уже готова (скрипт подключён в конце страницы) — запускаем сразу
    init();
  }
})();
