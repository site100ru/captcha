<?php
// =============================================================================
// КАПЧА «ПРИМЕР НА СЛОЖЕНИЕ» — ГЕНЕРАЦИЯ КАРТИНКИ
// =============================================================================
//
// Этот файл открывается браузером как картинка:
//     <img src="/captcha/captcha.php?1697712345678">
//
// Что он делает:
//   1. Придумывает пример из двух случайных чисел от 1 до 9 (например, 3 + 5).
//   2. Запоминает правильный ответ (8) в СЕССИИ посетителя.
//   3. Рисует пример на картинке PNG с «шумом» и отдаёт её браузеру.
//
// Сессия — это память сервера о конкретном посетителе. Браузер хранит только
// «номер» сессии в cookie, а сам ответ лежит на сервере. Поэтому подсмотреть
// ответ в коде страницы невозможно — его видно только на картинке.
//
// Проверку ответа делает функция captcha_is_valid() из файла captcha-check.php.
//
// ВАЖНО: правильным считается ответ только на ПОСЛЕДНИЙ показанный пример.
// Каждое новое открытие этого файла перезаписывает ответ в сессии.
//
// Требования: PHP 7.0+ и PHP-расширение GD (рисует картинки).
// Подробная инструкция по установке — в файле README.md в корне репозитория.
// =============================================================================

// Ключ, под которым правильный ответ хранится в сессии.
// Этот же ключ читает captcha-check.php — менять нужно в обоих файлах сразу.
$captcha_session_key = 'captcha';

// Размеры картинки в пикселях (ширина и высота).
// Если меняете — поменяйте и атрибуты width/height у <img> в форме.
$width  = 120;
$height = 40;

// Проверяем, что на сервере есть расширение GD: без него картинку не нарисовать.
// function_exists() возвращает true, если такая функция PHP существует.
if ( ! function_exists( 'imagecreatetruecolor' ) ) {
	// Отвечаем кодом 500 «Ошибка сервера», чтобы проблему было видно в логах
	http_response_code( 500 );
	// Сообщаем, что дальше идёт обычный текст, а не картинка
	header( 'Content-Type: text/plain; charset=utf-8' );
	// Текст ошибки для администратора (виден, если открыть адрес файла в браузере)
	echo 'Для капчи нужно PHP-расширение GD. Включите его в настройках PHP (php.ini) или попросите хостинг.';
	// Прекращаем выполнение файла
	exit;
}

// Включаем сессию, чтобы было куда записать правильный ответ.
// session_status() проверяет, не была ли сессия уже включена раньше
// (повторный session_start() выдал бы предупреждение).
if ( session_status() === PHP_SESSION_NONE ) {
	// Запускаем сессию: PHP прочитает cookie с номером сессии или создаст новую
	session_start();
}

// Первое случайное число от 1 до 9.
// random_int() — криптографически стойкий генератор (числа нельзя предсказать).
$a = random_int( 1, 9 );

// Второе случайное число от 1 до 9
$b = random_int( 1, 9 );

// Запоминаем правильный ответ в сессии. Это обычное число от 2 до 18.
$_SESSION[ $captcha_session_key ] = $a + $b;

// Сразу записываем и закрываем сессию: картинке она больше не нужна,
// а открытая сессия блокирует другие запросы того же посетителя.
session_write_close();

// Сообщаем браузеру, что отдаём картинку PNG, а не обычную страницу
header( 'Content-Type: image/png' );

// Запрещаем браузеру и прокси кешировать картинку. Иначе после обновления
// пользователь увидит старый пример, а в сессии будет уже новый ответ.
header( 'Cache-Control: no-store, no-cache, must-revalidate, max-age=0' );

// То же самое для старых браузеров и прокси, которые не понимают Cache-Control
header( 'Pragma: no-cache' );

// Дата «устаревания» в прошлом — ещё один способ сказать «не кешировать»
header( 'Expires: 0' );

// Создаём пустую цветную картинку нужного размера
$img = imagecreatetruecolor( $width, $height );

// Цвет фона: светло-серый (числа — это красный, зелёный, синий от 0 до 255)
$bg = imagecolorallocate( $img, 240, 240, 240 );

// Цвет текста: почти чёрный
$fg = imagecolorallocate( $img, 30, 30, 30 );

// Заливаем всю картинку цветом фона, начиная с левого верхнего угла (0, 0)
imagefill( $img, 0, 0, $bg );

// Шум: рисуем 30 случайных линий, чтобы пример было сложнее распознать программой
for ( $i = 0; $i < 30; $i++ ) {
	// Случайный бледный цвет для очередной линии (каждый канал от 150 до 220)
	$c = imagecolorallocate( $img, random_int( 150, 220 ), random_int( 150, 220 ), random_int( 150, 220 ) );
	// Линия из случайной точки (x1, y1) в случайную точку (x2, y2) внутри картинки
	imageline( $img, random_int( 0, $width ), random_int( 0, $height ), random_int( 0, $width ), random_int( 0, $height ), $c );
}

// Пишем сам пример встроенным шрифтом PHP (отдельный файл шрифта не нужен):
//   5  — размер шрифта (самый крупный из встроенных, от 1 до 5);
//   22 — отступ текста слева в пикселях;
//   12 — отступ текста сверху в пикселях.
imagestring( $img, 5, 22, 12, "$a + $b = ?", $fg );

// Отдаём готовую картинку в браузер в формате PNG
imagepng( $img );

// Освобождаем память, занятую картинкой
imagedestroy( $img );
