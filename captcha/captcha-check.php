// =============================================================================
// КАПЧА «ПРИМЕР НА СЛОЖЕНИЕ» — ПРОВЕРКА ОТВЕТА И ТЕЛЕФОНА
// =============================================================================
//
// Этот файл подключается в обработчике формы (в том PHP-файле, куда
// отправляется форма — её атрибут action):
//
//     require_once __DIR__ . '/captcha/captcha-check.php';
//
// После подключения доступны две функции:
//
//   captcha_is_valid( $_POST['captcha'] )
//       true  — посетитель правильно решил пример;
//       false — ответ неверный, пустой или картинку с примером не открывали.
//
//   captcha_phone_is_valid( $_POST['tel'] )
//       true  — телефон введён полностью по маске +7(999)999-99-99;
//       false — номер не дописан или записан в другом виде.
//
// Сам файл ничего не выводит и ничего не отправляет — только проверяет.
// Подробная инструкция по установке — в файле README.md в корне репозитория.
// =============================================================================

// Включаем сессию, если её ещё не включили раньше: правильный ответ на пример
// лежит в сессии (его туда записал captcha.php).
if ( session_status() === PHP_SESSION_NONE ) {
	// Запускаем сессию. ВАЖНО: до этого места нельзя ничего выводить в браузер
	// (ни HTML, ни пробелов перед <?php), иначе сессия не запустится.
	session_start();
}

// Объявляем функцию, только если её ещё нет — на случай, если файл
// по ошибке подключили дважды через require вместо require_once.
if ( ! function_exists( 'captcha_is_valid' ) ) {

	/**
	 * Проверяет ответ посетителя на пример с картинки.
	 *
	 * Ответ одноразовый: после проверки (удачной или нет) он удаляется
	 * из сессии. Для новой попытки посетителю нужно показать новую картинку.
	 *
	 * @param mixed $answer То, что посетитель ввёл в поле name="captcha".
	 * @return bool true — ответ правильный, false — неправильный.
	 */
	function captcha_is_valid( $answer ) {

		// Ключ в сессии — должен совпадать с $captcha_session_key в captcha.php
		$key = 'captcha';

		// Достаём правильный ответ из сессии. Если его там нет (картинку
		// не открывали — так обычно делают роботы), получаем null.
		$expected = isset( $_SESSION[ $key ] ) ? $_SESSION[ $key ] : null;

		// Сразу удаляем ответ из сессии, чтобы один и тот же ответ нельзя было
		// использовать для нескольких отправок формы подряд.
		unset( $_SESSION[ $key ] );

		// Пример не показывали — проверять не с чем, отказываем
		if ( $expected === null ) {
			return false;
		}

		// Ответ пришёл не текстом (например, массивом при поддельной отправке
		// формы) — отказываем. Без этой проверки trim() ниже вызвал бы ошибку.
		if ( ! is_string( $answer ) ) {
			return false;
		}

		// Убираем случайные пробелы в начале и в конце ответа
		$answer = trim( $answer );

		// Ответ должен состоять из 1–2 цифр: сумма двух чисел от 1 до 9 —
		// это максимум 18. Шаблон читается так:
		//   ^      — начало строки;
		//   \d{1,2} — одна или две цифры;
		//   \z     — конец строки, после цифр ничего быть не должно.
		if ( ! preg_match( '/^\d{1,2}\z/', $answer ) ) {
			return false;
		}

		// Превращаем текст в число и сравниваем с правильным ответом.
		// === — строгое сравнение: совпасть должны и значение, и тип (оба числа).
		return (int) $answer === (int) $expected;
	}
}

// Та же защита от повторного объявления функции, что и выше
if ( ! function_exists( 'captcha_phone_is_valid' ) ) {

	/**
	 * Проверяет, что телефон введён полностью по маске +7(999)999-99-99.
	 *
	 * Маска в браузере (tel-mask.js) не даёт ввести номер в другом виде,
	 * но браузерную проверку робот легко обходит, поэтому повторяем её на сервере.
	 *
	 * @param mixed $tel То, что пришло из поля name="tel".
	 * @return bool true — номер полный и правильного вида, false — нет.
	 */
	function captcha_phone_is_valid( $tel ) {

		// Телефон пришёл не текстом (поддельная отправка формы) — отказываем.
		// Без этой проверки preg_match() ниже вызвал бы ошибку.
		if ( ! is_string( $tel ) ) {
			return false;
		}

		// Сверяем номер с шаблоном. Как читать шаблон:
		//   ^      — номер должен начинаться сразу, без лишних символов впереди;
		//   \+     — знак плюс (обратная косая черта «\» нужна, чтобы плюс
		//            считался обычным символом, а не командой шаблона);
		//   7      — цифра семь (маска на сайте всегда подставляет именно её);
		//   \(     — открывающая скобка (косая черта — по той же причине, что у плюса);
		//   \d{3}  — три цифры (код оператора);
		//   \)     — закрывающая скобка;
		//   \d{3}  — три цифры;
		//   -      — дефис;
		//   \d{2}  — две цифры;
		//   -      — дефис;
		//   \d{2}  — две цифры;
		//   \z     — на этом номер заканчивается, после него ничего быть не должно.
		// preg_match() возвращает 1, если номер подошёл, и 0, если нет;
		// === 1 превращает это в true/false.
		return preg_match( '/^\+7\(\d{3}\)\d{3}-\d{2}-\d{2}\z/', $tel ) === 1;
	}
}
