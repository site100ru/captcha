/**
 * КАПЧА «ПРИМЕР НА СЛОЖЕНИЕ» — ПОКАЗ И ОБНОВЛЕНИЕ КАРТИНКИ
 *
 * Задача этого скрипта — вовремя загрузить картинку с примером:
 *   - форма во всплывающем окне Bootstrap (.modal) — новый пример
 *     при каждом открытии окна;
 *   - обычная форма на странице — пример загружается сразу при открытии страницы;
 *   - клик по картинке — новый пример (если плохо видно цифры).
 *
 * Картинку рисует captcha.php, он же запоминает правильный ответ в сессии.
 *
 * Почему картинка во всплывающем окне не грузится сразу вместе со страницей:
 * правильным считается ответ только на ПОСЛЕДНИЙ показанный пример. Если бы
 * картинки в двух окнах загрузились сразу, ответ из первого окна уже не подошёл бы.
 *
 * Что скрипт ищет на странице:
 *   <img class="captchaImg">       — картинка с примером (обязательно);
 *   <input name="captcha">         — поле ответа в той же форме (очищается
 *                                    при каждой смене примера).
 *
 * Адрес captcha.php скрипт определяет сам: файл должен лежать в той же папке,
 * что и captcha.js. Если он лежит в другом месте, укажите адрес у картинки:
 *   <img class="captchaImg" data-captcha-src="/путь/до/captcha.php">
 *
 * Подробная инструкция по установке — в файле README.md в корне репозитория.
 */

// Оборачиваем весь код в функцию, которая сразу же вызывается,
// чтобы наши переменные не смешивались с переменными других скриптов сайта
(function () {
  // Строгий режим: браузер сообщает о типичных ошибках в коде, а не молчит
  'use strict';

  // Тег <script>, который подключил этот файл (есть, пока скрипт выполняется)
  var script = document.currentScript;

  // Адрес captcha.php по умолчанию — в той же папке, что и этот скрипт.
  // Берём адрес скрипта, отрезаем «?…» и «#…» (если есть), затем отрезаем
  // имя файла после последней «/» и дописываем captcha.php.
  // Если адрес скрипта узнать не удалось — ищем captcha.php рядом со страницей.
  var defaultSrc = script
    ? script.src.split('#')[0].split('?')[0].replace(/[^\/]*$/, '') + 'captcha.php'
    : 'captcha.php';

  // Подготавливает одну картинку капчи: назначает загрузку и обновление примера
  function setupCaptcha(img) {
    // Адрес captcha.php: из атрибута data-captcha-src, а если его нет — по умолчанию
    var src = img.getAttribute('data-captcha-src') || defaultSrc;

    // Форма, в которой находится картинка (ближайший родитель <form>), или null
    var form = img.closest('form');

    // Поле ответа в этой же форме, если форма есть, иначе null
    var input = form ? form.querySelector('input[name="captcha"]') : null;

    // Всплывающее окно Bootstrap, в котором находится картинка, или null
    var modal = img.closest('.modal');

    // Загружает новый пример и очищает поле ответа
    function refreshCaptcha() {
      // Знак-разделитель: «?», если в адресе ещё нет параметров, иначе «&»
      var sep = src.indexOf('?') === -1 ? '?' : '&';

      // Date.now() добавляет к адресу текущее время, чтобы адрес каждый раз
      // был новым и браузер не показал старую картинку из кеша
      img.src = src + sep + Date.now();

      // Старый ответ к новому примеру не подходит — стираем его
      if (input) {
        input.value = '';
      }
    }

    // Подсказка при наведении, если её не задали в HTML
    if (!img.title) {
      img.title = 'Обновить пример';
    }

    // Курсор-«рука» над картинкой показывает, что по ней можно кликнуть
    img.style.cursor = 'pointer';

    // Клик по картинке — новый пример
    img.addEventListener('click', refreshCaptcha);

    if (modal) {
      // Форма во всплывающем окне: новый пример при каждом открытии окна.
      // show.bs.modal — событие Bootstrap «окно начинает открываться».
      modal.addEventListener('show.bs.modal', refreshCaptcha);
    } else {
      // Обычная форма на странице: загружаем пример сразу
      refreshCaptcha();
    }
  }

  // Находит на странице все картинки капчи и подготавливает каждую
  function init() {
    // querySelectorAll возвращает список всех элементов с классом captchaImg
    var images = document.querySelectorAll('.captchaImg');

    // Перебираем найденные картинки по одной
    for (var i = 0; i < images.length; i++) {
      // Подготавливаем очередную картинку
      setupCaptcha(images[i]);
    }
  }

  // Если страница ещё загружается — ждём, пока браузер построит всю разметку
  if (document.readyState === 'loading') {
    // DOMContentLoaded — событие «вся разметка страницы готова»
    document.addEventListener('DOMContentLoaded', init);
  } else {
    // Разметка уже готова (скрипт подключён в конце страницы) — запускаем сразу
    init();
  }
})();
